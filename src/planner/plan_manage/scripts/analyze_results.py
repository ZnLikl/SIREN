#!/usr/bin/env python3
import argparse
from pathlib import Path
import pandas as pd


def safe_metrics(df, candidates):
    return [c for c in candidates if c in df.columns]


def write_group_table(df, group_cols, metrics, out_path):
    if not group_cols or not metrics or df.empty:
        return None
    tbl = df.groupby(group_cols)[metrics].agg(["mean", "std", "count"])
    tbl.to_csv(out_path)
    return tbl


def relative_to_benign(df, group_cols, metrics, out_path):
    if "method" not in df.columns or "benign" not in set(df["method"]):
        return None
    base_cols = [c for c in group_cols if c != "method"]
    if not base_cols:
        return None
    benign = df[df.method == "benign"].groupby(base_cols)[metrics].mean()
    rows = []
    for key, sub in df.groupby(group_cols):
        key_tuple = key if isinstance(key, tuple) else (key,)
        key_map = dict(zip(group_cols, key_tuple))
        base_key = tuple(key_map[c] for c in base_cols)
        if len(base_cols) == 1:
            base_key = base_key[0]
        if base_key not in benign.index:
            continue
        base = benign.loc[base_key]
        cur = sub[metrics].mean()
        row = {c: key_map[c] for c in group_cols}
        for m in metrics:
            denom = max(abs(float(base[m])), 1e-9)
            row[m + "_rel_pct"] = 100.0 * (float(cur[m]) - float(base[m])) / denom
        rows.append(row)
    out = pd.DataFrame(rows)
    out.to_csv(out_path, index=False)
    return out


def ripple_table(per_uav, out_path):
    if per_uav is None or per_uav.empty or "role" not in per_uav.columns:
        return None
    metrics = safe_metrics(per_uav, [
        "replanning_count", "J_swarm_avg", "J_swarm_max", "trajectory_length",
        "completion_time", "mission_success", "min_inter_uav_distance"
    ])
    group_cols = [c for c in ["map", "scenario", "method", "role"] if c in per_uav.columns]
    return write_group_table(per_uav, group_cols, metrics, out_path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", help="trial-level summary.csv")
    ap.add_argument("--per-uav", default=None, help="optional per_uav.csv generated by run_experiments.py")
    ap.add_argument("--out-prefix", default="tables")
    ns = ap.parse_args()

    df = pd.read_csv(ns.csv)
    out_prefix = Path(ns.out_prefix)
    out_prefix.parent.mkdir(parents=True, exist_ok=True)

    group_cols = [c for c in ["map", "scenario", "method"] if c in df.columns]
    metrics = safe_metrics(df, [
        "mission_success",
        "completion_time",
        "trajectory_length",
        "replanning_count",
        "collision_replanning_count",
        "avg_planning_time",
        "max_planning_time",
        "J_swarm_avg",
        "J_swarm_max",
        "attack_score_avg",
        "attack_score_max",
        "min_inter_uav_distance",
        "victim_deviation_max",
        "victim_deviation_avg",
        "trap_dwell_time",
        "deadlock_duration",
        "goal_oscillation_count",
        "max_velocity",
        "max_acceleration",
        "max_jerk",
        "timestamp_deviation",
        "current_position_residual",
        "current_velocity_residual",
        "uwb_residual",
        "physical_check_pass",
        "detection_flag",
    ])

    overall = write_group_table(df, group_cols, metrics, str(out_prefix) + "_overall.csv")
    if overall is not None:
        print("[OVERALL]")
        print(overall)

    rel = relative_to_benign(df, group_cols, metrics, str(out_prefix) + "_relative_to_benign.csv")
    if rel is not None:
        print("[RELATIVE TO BENIGN]")
        print(rel)

    if ns.per_uav:
        per = pd.read_csv(ns.per_uav)
        rip = ripple_table(per, str(out_prefix) + "_ripple_by_role.csv")
        if rip is not None:
            print("[RIPPLE BY ROLE]")
            print(rip)

        per_metrics = safe_metrics(per, [
            "mission_success", "completion_time", "trajectory_length", "replanning_count",
            "collision_replanning_count", "J_swarm_avg", "J_swarm_max", "min_inter_uav_distance",
            "max_velocity", "max_acceleration", "max_jerk", "physical_check_pass", "detection_flag"
        ])
        per_group = [c for c in ["map", "scenario", "method", "uav_id", "role"] if c in per.columns]
        write_group_table(per, per_group, per_metrics, str(out_prefix) + "_per_uav_detail.csv")


if __name__ == "__main__":
    main()
